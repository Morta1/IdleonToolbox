// Writes utility/wiki/game-constants.mjs: the website-data tables the wiki's client modules read (utility/wiki/effects.mjs,
// notate.js, components/wiki). Those modules run in the browser and must not import @website-data, so they read this
// generated module instead. It runs as its own process before build.mjs (npm run build:graph): an import inside
// build.mjs's process would read the file the previous run wrote.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { loadWebsiteData, missingTablesLine } from './registry/data.mjs';
import { READ as core } from './game-constants/core.mjs';
import { READ as l1 } from './game-constants/l1.mjs';
import { READ as l2 } from './game-constants/l2.mjs';
import { READ as l3 } from './game-constants/l3.mjs';
import { READ as l4 } from './game-constants/l4.mjs';
import { READ as l5 } from './game-constants/l5.mjs';
import { READ as l6 } from './game-constants/l6.mjs';
import { READ as l7 } from './game-constants/l7.mjs';
import { READ as l8 } from './game-constants/l8.mjs';

// The reads of each file in game-constants/: core, then one per wiki upkeep lane, so lanes never edit one file.
const FILES = { core, l1, l2, l3, l4, l5, l6, l7, l8 };
const READ = {};
for (const [file, reads] of Object.entries(FILES)) {
  for (const [name, read] of Object.entries(reads)) {
    if (name in READ) throw new Error(`game-constants/${file}.mjs: ${name} is read twice`);
    READ[name] = read;
  }
}
export const CLIENT_TABLES = Object.keys(READ).sort();
// Owner decisions 6: without these the wiki prints no number the game's way, which is worse than a held deploy.
export const CORE_TABLES = ['formatBonuses', 'notateNumber'];

// The client tables by name, sorted. An absent one is left out and named (Owner decisions 4); an absent core one throws.
export const gameConstants = (data) => {
  const out = {};
  const missing = [];
  for (const name of CLIENT_TABLES) {
    const table = READ[name](data);
    if (table === null) missing.push(name);
    else out[name] = table;
  }
  const core = missing.filter((name) => CORE_TABLES.includes(name));
  if (core.length) throw new Error(`missing gameTables: ${core.join(', ')} (the wiki formats numbers with them, so the build stops; run npm run test:analysis in z-processing)`);
  if (missing.length) console.warn(missingTablesLine(missing));
  return out;
};

export const moduleText = (constants) => [
  '// Generated by scripts/entity-graph/game-constants.mjs from data/website-data (npm run build:graph): do not edit.',
  '// Each key is the website-data table of the same name.',
  `export default ${JSON.stringify(constants, null, 2)};`,
  ''
].join('\n');

const self = fileURLToPath(import.meta.url);
// Run as a script, never when imported. Compared by real path: through a junction or symlink, argv[1] keeps the path
// typed while import.meta.url is the real one, and a plain comparison would skip the write without a word.
const entry = process.argv[1] ? path.resolve(process.argv[1]) : null;
const isEntry = Boolean(entry) && fs.existsSync(entry) && fs.realpathSync.native(entry) === fs.realpathSync.native(self);
if (isEntry) {
  const root = path.join(path.dirname(self), '..', '..');
  // `--out <file>` writes elsewhere (the test that runs it through a link).
  const at = process.argv.indexOf('--out');
  const out = at > 0 ? path.resolve(process.argv[at + 1]) : path.join(root, 'utility', 'wiki', 'game-constants.mjs');
  fs.writeFileSync(out, moduleText(gameConstants(loadWebsiteData(path.join(root, 'data', 'website-data')))));
  console.log(`[game-constants] wrote ${path.relative(root, out).split(path.sep).join('/')}`);
}
